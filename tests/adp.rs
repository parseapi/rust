use parseapi::*;
#[test] fn root_models_keep_core_and_decode_detail() {
let plain: Country=serde_json::from_str(r#"{"country":"US","name":"United States","continent":"NA"}"#).unwrap();
let rich: Country=serde_json::from_str(r#"{"country":"US","name":"United States","continent":"NA","iso3":"USA","population":0,"tax_rate":0,"plugs":[]}"#).unwrap();
assert_eq!(plain.country,rich.country);
assert_eq!(rich.population,Some(0));
let plain: State=serde_json::from_str(r#"{"state":"NC","name":"North Carolina","country":"US"}"#).unwrap();
let rich: State=serde_json::from_str(r#"{"state":"NC","name":"North Carolina","country":"US","population":0,"area":0.25,"tax_rate":0}"#).unwrap();
assert_eq!(plain.state,rich.state);
assert_eq!(rich.population,Some(0));
let plain: District=serde_json::from_str(r#"{"district":"37081","name":"Guilford","country":"US"}"#).unwrap();
let rich: District=serde_json::from_str(r#"{"district":"37081","name":"Guilford","country":"US","population":0,"water_area":0.25}"#).unwrap();
assert_eq!(plain.district,rich.district);
assert_eq!(rich.population,Some(0));
let plain: City=serde_json::from_str(r#"{"name":"Charlotte","country":"US","id":"city_123"}"#).unwrap();
let rich: City=serde_json::from_str(r#"{"name":"Charlotte","country":"US","id":"city_123","population":0,"area":0.25}"#).unwrap();
assert_eq!(plain.name,rich.name);
assert_eq!(rich.population,Some(0));
let plain: Postal=serde_json::from_str(r#"{"postal":"28202","country":"US"}"#).unwrap();
let rich: Postal=serde_json::from_str(r#"{"postal":"28202","country":"US","metros":[],"water_area":0.25,"tax_rate":0}"#).unwrap();
assert_eq!(plain.postal,rich.postal);
assert_eq!(rich.water_area,Some(0.25));
let plain: Phone=serde_json::from_str(r#"{"phone":"+14155552671","valid":true}"#).unwrap();
let rich: Phone=serde_json::from_str(r#"{"phone":"+14155552671","valid":true,"state":"CA","timezone":"America/Los_Angeles"}"#).unwrap();
assert_eq!(plain.phone,rich.phone);
assert_eq!(rich.state.as_deref(),Some("CA"));
let plain: Carrier=serde_json::from_str(r#"{"phone":"+14155552671","valid":true,"carrier":"Example"}"#).unwrap();
let rich: Carrier=serde_json::from_str(r#"{"phone":"+14155552671","valid":true,"carrier":"Example","city":"San Francisco","state":"CA"}"#).unwrap();
assert_eq!(plain.phone,rich.phone);
assert_eq!(rich.city.as_deref(),Some("San Francisco"));
let plain: Hlr=serde_json::from_str(r#"{"phone":"+14155552671","valid":true,"live":true,"connected":false}"#).unwrap();
let rich: Hlr=serde_json::from_str(r#"{"phone":"+14155552671","valid":true,"live":true,"connected":false,"roaming":false,"mcc":"310","mnc":"01"}"#).unwrap();
assert_eq!(plain.phone,rich.phone);
assert_eq!(rich.roaming,Some(false));
let plain: Industry=serde_json::from_str(r#"{"naics":"541511","name":"Programming","level":6,"parent":"54151","year":2022,"country":"US"}"#).unwrap();
let rich: Industry=serde_json::from_str(r#"{"naics":"541511","name":"Programming","level":6,"parent":"54151","year":2022,"country":"US","description":"Definition","children":[],"exclusions":[]}"#).unwrap();
assert_eq!(plain.name,rich.name);
assert_eq!(rich.description.as_deref(),Some("Definition"));
let plain: Company=serde_json::from_str(r#"{"company":"01234567","valid":true,"name":"Example"}"#).unwrap();
let rich: Company=serde_json::from_str(r#"{"company":"01234567","valid":true,"name":"Example","activity":"6201","gst":false,"vat":null}"#).unwrap();
assert_eq!(plain.company,rich.company);
assert_eq!(rich.gst,Some(false));
let plain: Language=serde_json::from_str(r#"{"language":"en","name":"English","direction":"ltr"}"#).unwrap();
let rich: Language=serde_json::from_str(r#"{"language":"en","name":"English","direction":"ltr","iso3":"eng","countries":[]}"#).unwrap();
assert_eq!(plain.language,rich.language);
assert_eq!(rich.countries,Some(vec![]));
let plain: Name=serde_json::from_str(r#"{"name":"Andrea","valid":true,"first":"Andrea"}"#).unwrap();
let rich: Name=serde_json::from_str(r#"{"name":"Andrea","valid":true,"first":"Andrea","gender":null,"salutation":null}"#).unwrap();
assert_eq!(plain.name,rich.name);
assert_eq!(rich.salutation,None);
let plain: Timezone=serde_json::from_str(r#"{"timezone":"UTC","unix":0,"at":"1970-01-01T00:00:00+00:00","offset":"+00:00","dst":false}"#).unwrap();
let rich: Timezone=serde_json::from_str(r#"{"timezone":"UTC","unix":0,"at":"1970-01-01T00:00:00+00:00","offset":"+00:00","dst":false,"name":"UTC","offset_seconds":0,"offset_minutes":0,"next_dst":null}"#).unwrap();
assert_eq!(plain.timezone,rich.timezone);
assert_eq!(rich.offset_seconds,Some(0));
let plain: DateInfo=serde_json::from_str(r#"{"date":"1970-01-01","valid":true,"unix":0}"#).unwrap();
let rich: DateInfo=serde_json::from_str(r#"{"date":"1970-01-01","valid":true,"unix":0,"year":1970,"weekday":4,"leap":false}"#).unwrap();
assert_eq!(plain.date,rich.date);
assert_eq!(rich.leap,Some(false));
let plain: Emoji=serde_json::from_str(r#"{"emoji":"😀","name":"grinning face","shortcodes":[]}"#).unwrap();
let rich: Emoji=serde_json::from_str(r#"{"emoji":"😀","name":"grinning face","shortcodes":[],"hex":"1F600","skins":[]}"#).unwrap();
assert_eq!(plain.emoji,rich.emoji);
assert_eq!(rich.hex.as_deref(),Some("1F600"));
let plain: Point=serde_json::from_str(r#"{"latitude":0,"longitude":0,"timezone":"Etc/GMT"}"#).unwrap();
let rich: Point=serde_json::from_str(r#"{"latitude":0,"longitude":0,"timezone":"Etc/GMT","elevation":0.25,"city":{"name":"Place","id":"city_123","type":"city","distance":0.5}}"#).unwrap();
assert_eq!(plain.latitude,rich.latitude);
assert_eq!(rich.elevation,Some(0.25));
let plain: Weather=serde_json::from_str(r#"{"latitude":0,"longitude":0,"current":{"temperature":0,"observed_at":"2026-09-08T12:00:00Z"}}"#).unwrap();
let rich: Weather=serde_json::from_str(r#"{"latitude":0,"longitude":0,"current":{"temperature":0,"observed_at":"2026-09-08T12:00:00Z","pressure":1012.5,"wind_gust":0},"forecast":[]}"#).unwrap();
assert_eq!(plain.latitude,rich.latitude);
assert_eq!(rich.current.pressure,Some(1012.5));
}
#[test]
fn nested_district_profiles_and_clock_targets_preserve_zero() {
 let listing: StateDistricts = serde_json::from_str(r#"{"state":"NC","country":"US","districts":[{"district":"37081","name":"Guilford","population":0}]}"#).unwrap();
 assert_eq!(listing.districts[0].population,Some(0));
 let clock: Time = serde_json::from_str(r#"{"timezone":"UTC","unix":0,"to":{"timezone":"UTC","unix":0,"offset_seconds":0},"offset_seconds":0,"next_dst":null}"#).unwrap();
 assert_eq!(clock.to.unwrap().offset_seconds,Some(0));
}
